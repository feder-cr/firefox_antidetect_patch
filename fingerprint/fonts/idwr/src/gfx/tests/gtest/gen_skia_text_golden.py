# Writes StealthSkiaIdwrGolden.inc: the glyph masks DirectWrite (System32\DWrite.dll, Windows only)
# gives Skia's call pattern, which TestStealthSkiaIdwr.cpp compares with what DrawTargetSkia draws
# through ScaledFont and idwr. The cases are invisible_DWriteCore's reimpl/texture_check.py skia_case
# (the arithmetic of SkScalerContext_DW's constructor, generateDWMetrics and getDWMaskBits), run
# through its DWrite class on copies of the bundle fonts.
#
#   python -I gfx/tests/gtest/gen_skia_text_golden.py --dwritecore C:/Users/feder/invisible_DWriteCore \
#       --fonts C:/ff/source/browser/fonts --out gfx/tests/gtest/StealthSkiaIdwrGolden.inc
#
# The variable instances need skia_case's ax argument (the idwr study's texture_check.py of the
# skiaaxes group, which also checks idwr against DirectWrite on a larger set of the same cases).
#
# One row per glyph: font, em size, glyph, subpixel x (quarters), bounds, FNV-1a 64 of the A8 mask,
# and for a variable instance its axes ("wght=700,wdth=75").
# Glyphs DirectWrite gives empty bounds (spaces) are left out: Skia draws nothing for them.
import argparse, importlib.util, os, sys, tempfile

FONTS = ['arial7_04.ttf', 'calibri6_26.ttf', 'times7_11.ttf']
SIZES = [9.0, 12.5, 16.0, 33.0]
TEXT = 'Hamburgefonstiv 0123'
OFFSETS = [0.0, 0.25, 0.5, 0.75]

# Variable instances: the bundle's variable fonts at wght 300, 400 (the default of both) and 700,
# every other axis at its default, and Bahnschrift's two axes together (the order of the axes).
# The tests make the scaled font with these variations; idwr and DirectWrite open the instance.
AXIS_FONTS = [
    ('seguivar2_03.ttf', [[('wght', 300.0)], [('wght', 400.0)], [('wght', 700.0)]]),
    ('bahnschrift2_07.ttf', [[('wght', 300.0)], [('wght', 400.0)], [('wght', 700.0)],
                             [('wght', 700.0), ('wdth', 75.0)]]),
]
AXIS_SIZES = [12.5, 33.0]
AXIS_OFFSETS = [0.0, 0.5]


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--dwritecore', required=True)
    p.add_argument('--fonts', required=True)
    p.add_argument('--out', required=True)
    a = p.parse_args()
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location('texture_check',
                                                  os.path.join(a.dwritecore, 'reimpl', 'texture_check.py'))
    tc = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(tc)
    tmp = tempfile.mkdtemp(prefix='skia_golden_')
    os.makedirs(os.path.join(tmp, 'fonts'))
    dw = tc.DWrite(os.path.join(tmp, 'fonts'))
    smoothing = tc.compatible_smoothing()
    rows = []

    def add(name, ax, sizes, offsets):
        path = os.path.join(a.fonts, name)
        (i, tables, data), = tc.sfnt_faces(path)
        gids = dw.glyph_indices({'f': path, 'i': 0, 's': 0, 'ax': None}, TEXT)
        glyphs = sorted({g for ch, g in zip(TEXT, gids) if ch != ' '})
        for em in sizes:
            for gid in glyphs:
                for off in offsets:
                    c = tc.skia_case(path, i, tables, data, gid, em, (1.0, 0.0, 0.0, 1.0), 'a8', (off, 0.0),
                                     ax=ax)
                    res, pixels = tc.run_case(dw, c, smoothing, True)
                    hr, mode, tex, bhr, rect, thr, sha, size = res
                    if hr != 0 or bhr != 0 or rect is None or pixels is None or thr != 0:
                        continue
                    # a Skia mask is the A8 texture, or (retry) the aliased one, as 0/255
                    rows.append((name, em, gid, off, rect, fnv1a64(pixels), mode, tex, ax))

    for name in FONTS:
        add(name, None, SIZES, OFFSETS)
    for name, instances in AXIS_FONTS:
        for ax in instances:
            add(name, ax, AXIS_SIZES, AXIS_OFFSETS)
    with open(a.out, 'w', newline='\n') as f:
        f.write('// Generated by gen_skia_text_golden.py, do not edit. DirectWrite 10.0.26100.9711 masks of\n')
        f.write('// Skia\'s call pattern (A8, grid fit enabled, hinting normal), bundled fonts, identity matrix.\n')
        f.write('// font, em, glyph, subpixel x, left, top, right, bottom, FNV-1a 64 of the mask, mode, texture\n')
        f.write('// and, for a variable instance, its axes\n')
        for name, em, gid, off, r, h, mode, tex, ax in rows:
            # the rows of the default face stop at the texture; an instance adds its axes
            tail = '' if ax is None else ', "%s"' % ','.join('%s=%g' % (t, v) for t, v in ax)
            f.write('{"%s", %.2ff, %d, %.2ff, %d, %d, %d, %d, 0x%016xULL, %d, %d%s},\n' %
                    (name, em, gid, off, r[0], r[1], r[2], r[3], h, mode, tex, tail))
    print(len(rows), 'cases ->', a.out)


if __name__ == '__main__':
    main()
