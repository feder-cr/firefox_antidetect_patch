/*
 * Post-processing of the scan converter's 1-bit bitmaps in fs_ContourScan (DWrite.dll
 * 10.0.26100.9711): gray maps from the overscaled bitmap (fsc_CalcGrayMap, the GDI
 * compatible fsc_CalcGrayMapGdiCompatible + fsc_CalcGrayRow), the overscaled bitmap to
 * ClearType subpixels (fsc_OverscaleToSubPixel), the bold simulation on the overscaled
 * bitmap (fsc_OverscaleToBold with EmboldenOverscaleConst and FindNext), the row fills used
 * by fsc_FillBitMap (fsc_BLTHoriz, fsc_BLTHorizReverseBitOrder) and ReverseBitOrder.
 *
 * GlyphBitMap (raw offsets): +0 rowBytes (int16), +2 top, +4 left, +6 bottom, +8 right
 * (int16, y up: rows = top - bottom), +0x1c byte size (int32), +0x20 bits.
 *
 * Calls between the functions of this file go through the original RVA, so that each one
 * can be swapped alone (oracle.py --swap): with the swap in place the original entry jumps
 * here. Tables are copied byte for byte from the DLL (RVA given with each).
 */
