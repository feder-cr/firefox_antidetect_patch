"""Generates StealthColorProfileCurve.inc, the sRGB tone curve of the system
colour profile that StealthColorProfile.cpp declares as the output profile.

The curve is the one of Windows' "sRGB Color Space Profile.icm" (3144 bytes,
sha256 2b3aa1645779a9e634744faf9b01e9102b0c9b88fd6deced7934df86b949af7e, as
found in System32\\spool\\drivers\\color on Windows 11 build 26100/26300): a
`curv` of 1024 points, point i = round(65535 * linear(i / 1023)), with
linear(x) = x / 12.92 for x <= 0.04045, else ((x + 0.055) / 1.055) ** 2.4,
rounded half to even as Python's round() does on a float64. Measured against
that file by reverse engineering: 1024 of 1024 points equal, in each of the
three channels (the three tags share one table).

The table is written in the source as constants, not computed at run time:
pow() differs between libm implementations, and the same seed must give the
same bytes on every machine.

Usage (standard library only):
  gen_stealth_color_profile.py            write StealthColorProfileCurve.inc
  gen_stealth_color_profile.py --check    fail if the .inc on disk is not what
                                          this script generates
  gen_stealth_color_profile.py --icm PATH also compare the table with the
                                          `curv` of an ICC file (the Windows
                                          profile, when present) and say so
  gen_stealth_color_profile.py --sha256   print the sha256 of the table and of
                                          the whole profile as assembled below
  gen_stealth_color_profile.py --write-profile OUT
                                          write the profile's bytes to OUT

build_profile() is the same assembly as StealthSystemColorProfileData() in
StealthColorProfile.cpp; the gtest pins the sha256 of its result, so the two
implementations are held equal by it.
"""

import hashlib
import os
import struct
import sys

POINTS = 1024
HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.join(HERE, "StealthColorProfileCurve.inc")

# The Windows profile's colorants and white point, raw s15Fixed16 (REA of the
# file above). These are D50-adapted sRGB primaries.
ILLUMINANT = (0x0000F6D6, 0x00010000, 0x0000D32D)  # 0.964203, 1.0, 0.824905
WTPT = (62289, 65536, 71372)
RXYZ = (28578, 14581, 912)
GXYZ = (25241, 46981, 6362)
BXYZ = (9376, 3972, 46799)


def linear(x):
    if x <= 0.04045:
        return x / 12.92
    return ((x + 0.055) / 1.055) ** 2.4


def curve():
    return [int(round(65535 * linear(i / (POINTS - 1)))) for i in range(POINTS)]


def inc_text(table):
    lines = [
        "/* This Source Code Form is subject to the terms of the Mozilla Public",
        " * License, v. 2.0. If a copy of the MPL was not distributed with this",
        " * file, You can obtain one at http://mozilla.org/MPL/2.0/. */",
        "",
        "// Generated by gen_stealth_color_profile.py; do not edit. The 1024 points of",
        "// the sRGB curve of the Windows system colour profile: point i is",
        "// round(65535 * linear(i / 1023)).",
        "",
    ]
    for r in range(0, POINTS, 16):
        lines.append("    " + " ".join("%d," % v for v in table[r:r + 16]))
    return "\n".join(lines) + "\n"


def xyz_tag(xyz):
    return b"XYZ " + b"\0\0\0\0" + struct.pack(">3i", *xyz)


def build_profile(table=None):
    table = table if table is not None else curve()
    tags_data = [
        (b"wtpt", xyz_tag(WTPT)),
        (b"rXYZ", xyz_tag(RXYZ)),
        (b"gXYZ", xyz_tag(GXYZ)),
        (b"bXYZ", xyz_tag(BXYZ)),
    ]
    curv = b"curv" + b"\0\0\0\0" + struct.pack(">I", POINTS) + struct.pack(
        ">%dH" % POINTS, *table)
    n_tags = 7
    offset = 128 + 4 + 12 * n_tags
    entries = b""
    body = b""
    for sig, data in tags_data:
        entries += sig + struct.pack(">II", offset + len(body), len(data))
        body += data
    curv_offset = offset + len(body)
    for sig in (b"rTRC", b"gTRC", b"bTRC"):
        entries += sig + struct.pack(">II", curv_offset, len(curv))
    body += curv
    size = offset + len(body)
    header = bytearray(128)
    struct.pack_into(">I", header, 0, size)
    struct.pack_into(">I", header, 8, 0x02100000)  # version 2.1.0
    header[12:16] = b"mntr"
    header[16:20] = b"RGB "
    header[20:24] = b"XYZ "
    header[36:40] = b"acsp"
    header[40:44] = b"MSFT"
    struct.pack_into(">I", header, 64, 0)  # rendering intent: perceptual
    struct.pack_into(">3I", header, 68, *ILLUMINANT)
    return bytes(header) + struct.pack(">I", n_tags) + entries + body


def icm_curve(path):
    d = open(path, "rb").read()
    n_tags = struct.unpack_from(">I", d, 128)[0]
    tables = {}
    for i in range(n_tags):
        sig, off, size = struct.unpack_from(">4sII", d, 132 + 12 * i)
        if sig in (b"rTRC", b"gTRC", b"bTRC"):
            if d[off:off + 4] != b"curv":
                return None
            n = struct.unpack_from(">I", d, off + 8)[0]
            tables[sig] = list(struct.unpack_from(">%dH" % n, d, off + 12))
    return tables


def main(argv):
    table = curve()
    text = inc_text(table)
    args = argv[1:]
    if "--check" in args:
        current = open(INC, encoding="utf8").read() if os.path.exists(INC) else ""
        if current != text:
            print("StealthColorProfileCurve.inc is not what the script generates")
            return 1
        print("StealthColorProfileCurve.inc is up to date")
    elif "--sha256" not in args and "--write-profile" not in args \
            and "--icm" not in args:
        with open(INC, "w", encoding="utf8", newline="\n") as f:
            f.write(text)
        print("wrote", INC)
    if "--icm" in args:
        path = args[args.index("--icm") + 1]
        if not os.path.exists(path):
            print("no ICC file at", path, "- nothing to compare")
        else:
            tables = icm_curve(path)
            if not tables:
                print("the ICC file has no curv tables")
                return 1
            for sig, t in sorted(tables.items()):
                same = sum(1 for a, b in zip(t, table) if a == b) \
                    if len(t) == POINTS else 0
                print("%s: %d/%d points equal to the generated table"
                      % (sig.decode(), same, POINTS))
                if same != POINTS:
                    return 1
    if "--sha256" in args:
        print("table sha256   ", hashlib.sha256(
            struct.pack(">%dH" % POINTS, *table)).hexdigest())
        profile = build_profile(table)
        print("profile sha256 ", hashlib.sha256(profile).hexdigest(),
              "(%d bytes)" % len(profile))
    if "--write-profile" in args:
        out = args[args.index("--write-profile") + 1]
        with open(out, "wb") as f:
            f.write(build_profile(table))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
