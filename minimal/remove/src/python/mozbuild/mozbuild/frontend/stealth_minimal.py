# Our directories, built only in the minimal engine, by the directory that lists them. The
# kept chrome files of a parent's dropped directories are built from that same parent, so
# they land in the same chrome directory (browser/ and devtools/ install under browser/).
ADD = {
    # what the build options leave out but a page can read, and the actor cleanup
    "toolkit": ["stealth-minimal"],
    # the chrome files of the dropped directories (generated by keep_jar.py)
    "toolkit/components": ["/toolkit/stealth-minimal/kept"],
    "browser/components": ["/browser/stealth-minimal"],
    "devtools": ["/devtools/stealth-minimal"],
}


def prune(context):
    """Drops this directory's DIRS entries listed in DROP and adds its ADD entry."""
    rel = context.relsrcdir
    dirs = context["DIRS"]
    for name in DROP.get(rel, []):
        # Some entries exist only on some platforms or configurations (push, profiles, ...).
        if name in dirs:
            dirs.remove(name)
    if rel in ADD:
        context["DIRS"] += ADD[rel]
