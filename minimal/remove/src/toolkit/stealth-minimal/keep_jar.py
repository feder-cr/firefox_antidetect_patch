"""The jar.mn that keeps what the dropped directories put in chrome packages.

The minimal engine leaves directories out of the build (mozbuild/frontend/stealth_minimal.py),
but what they
install into chrome packages stays, byte for byte: those packages can be readable by any
page (chrome://global/content/, chrome://browser/content/ are contentaccessible), and a
registered package name can be probed. So only their code goes: modules, components,
native code. This script copies their jar.mn files into one, with every source path made
absolute, and stops on any form it does not know instead of guessing.

    python3 toolkit/stealth-minimal/keep_jar.py           # rewrite the kept jar.mn files
    python3 toolkit/stealth-minimal/keep_jar.py --check   # fail if they are out of date
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

TOP = Path(__file__).resolve().parents[2]
TABLE = TOP / "python" / "mozbuild" / "mozbuild" / "frontend" / "stealth_minimal.py"
# Where the kept entries of each parent directory are built: the jar must land in the
# same chrome directory as the original (browser/ installs under the browser subdir).
KEEP_DIR = {"browser/components": "browser/stealth-minimal"}
ENTRY = re.compile(r"^(\s*)(\*?\+?\s*)(\S+)(\s+)\((.+)\)\s*$")
BARE = re.compile(r"^(\s*)(\*?\+?\s*)([\w.\-/@+]+)\s*$")
HEADER = """# This Source Code Form is subject to the terms of the Mozilla Public
# License, v. 2.0. If a copy of the MPL was not distributed with this
# file, You can obtain one at http://mozilla.org/MPL/2.0/.

# GENERATED by toolkit/stealth-minimal/keep_jar.py from the jar.mn files of the
# directories stealth_minimal.py leaves out of the minimal engine: their chrome files and
# registrations stay, the same bytes as retail, because a page can read or probe them.
"""


def dropped() -> dict[str, list[str]]:
    """The DROP table of stealth_minimal.py, read without importing mozbuild."""
    tree = ast.parse(TABLE.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "DROP":
            return ast.literal_eval(node.value)
    raise SystemExit("stealth_minimal.py has no DROP table")


def rewrite(jar: Path) -> list[str]:
    base = jar.parent.relative_to(TOP).as_posix()
    out = [f"# ---- {jar.relative_to(TOP).as_posix()}"]
    for n, line in enumerate(jar.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or stripped.startswith("%") or re.match(r"^[\w.\-/]+\.jar:$", stripped):
            # comments, preprocessor directives, registrations, jar headers: as written
            if stripped.startswith("% ") and "%" in stripped[2:] and stripped.split()[1] in ("locale",):
                raise SystemExit(f"{jar}:{n}: locale registration, not handled: {line}")
            out.append(line)
            continue
        if stripped.startswith("relativesrcdir") or stripped.startswith("["):
            raise SystemExit(f"{jar}:{n}: {stripped.split()[0]} not handled")
        m = ENTRY.match(line)
        if m:
            indent, star, dest, sp, src = m.groups()
        else:
            # No source: jar.py takes the destination's basename in the jar.mn's directory.
            bare = BARE.match(line)
            if not bare:
                raise SystemExit(f"{jar}:{n}: entry not understood: {line}")
            indent, star, dest = bare.groups()
            sp, src = " ", dest.rsplit("/", 1)[-1]
        if src.startswith("%"):
            raise SystemExit(f"{jar}:{n}: locale-relative source, not handled: {line}")
        if src.startswith("!/") or src.startswith("/"):
            pass
        elif src.startswith("!"):
            src = f"!/{base}/{src[1:]}"
        else:
            src = f"/{base}/{src[2:] if src.startswith('./') else src}"
        out.append(f"{indent}{star}{dest}{sp}({src})")
    return out


def render(parent: str, names: list[str]) -> str:
    parts = [HEADER]
    for name in names:
        for jar in sorted((TOP / parent / name).glob("**/jar.mn")):
            if "/test" in jar.as_posix():
                continue
            parts.append("\n".join(rewrite(jar)))
    return "\n\n".join(parts) + "\n"


def main(argv) -> int:
    check = "--check" in argv
    stale = []
    for parent, names in dropped().items():
        # A name stealth_minimal.py drops must be one its parent lists: a typo or a port that
        # renames a directory would otherwise keep it in the build without a word.
        listed = (TOP / parent / "moz.build").read_text(encoding="utf-8")
        unknown = [n for n in names if f'"{n}"' not in listed]
        if unknown:
            raise SystemExit(f"{parent}/moz.build does not list {unknown}")
        if parent not in KEEP_DIR:
            # No kept jar for this parent: none of its dropped directories may ship chrome files.
            jars = [j for n in names for j in (TOP / parent / n).glob("**/jar.mn") if "/test" not in j.as_posix()]
            if jars:
                raise SystemExit(f"{parent}: dropped directories with chrome files need a kept jar: {jars}")
            continue
        target = TOP / KEEP_DIR[parent] / "jar.mn"
        text = render(parent, names)
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                stale.append(str(target))
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {target.relative_to(TOP)}")
    if stale:
        print("out of date, rerun keep_jar.py: " + ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
